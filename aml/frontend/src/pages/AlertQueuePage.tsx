import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { api } from '../services/api';
import { Alert } from '../types';
import { SHAPModal } from '../components/alerts/SHAPModal';
import { AlertTriangle, Filter, Brain, Search } from 'lucide-react';

export const AlertQueuePage: React.FC = () => {
  const navigate = useNavigate();
  const [alerts, setAlerts] = useState<Alert[]>([]);
  const [priorityFilter, setPriorityFilter] = useState('ALL');
  const [statusFilter, setStatusFilter] = useState('ALL');
  const [loading, setLoading] = useState(true);
  const [searchTerm, setSearchTerm] = useState('');

  // SHAP Modal state
  const [selectedShap, setSelectedShap] = useState<any>(null);
  const [selectedAlertId, setSelectedAlertId] = useState<string>('');
  const [isShapOpen, setIsShapOpen] = useState(false);

  const fetchAlerts = () => {
    setLoading(true);
    api.get(`/alerts?priority=${priorityFilter}&status=${statusFilter}`)
      .then(res => setAlerts(res.data))
      .catch(err => console.error(err))
      .finally(() => setLoading(false));
  };

  useEffect(() => {
    fetchAlerts();
  }, [priorityFilter, statusFilter]);

  const handleOpenShap = (alert: Alert) => {
    setSelectedAlertId(alert.alert_id);
    if (alert.shap_explanation) {
      try {
        setSelectedShap(JSON.parse(alert.shap_explanation));
      } catch {
        setSelectedShap(null);
      }
    } else {
      setSelectedShap(null);
    }
    setIsShapOpen(true);
  };

  const getPriorityBadge = (priority: string) => {
    switch (priority) {
      case 'CRITICAL': return 'text-[#EF4444] bg-[#EF4444]/10 border-[#EF4444]/40';
      case 'HIGH': return 'text-[#F59E0B] bg-[#F59E0B]/10 border-[#F59E0B]/40';
      case 'MEDIUM': return 'text-[#3B82F6] bg-[#3B82F6]/10 border-[#3B82F6]/40';
      default: return 'text-[#22C55E] bg-[#22C55E]/10 border-[#22C55E]/40';
    }
  };

  const filteredAlerts = alerts.filter(a => 
    !searchTerm || 
    a.alert_id.toLowerCase().includes(searchTerm.toLowerCase()) || 
    (a.customer_id && a.customer_id.toLowerCase().includes(searchTerm.toLowerCase())) ||
    a.typology.toLowerCase().includes(searchTerm.toLowerCase())
  );

  return (
    <div className="space-y-5 select-none">
      <div className="flex flex-wrap items-center justify-between gap-4 border-b border-[#202A35] pb-3">
        <div>
          <h1 className="text-sm font-bold text-[#E8EDF2] tracking-tight flex items-center space-x-2">
            <AlertTriangle className="w-4 h-4 text-[#F59E0B]" />
            <span>AML Suspicious Alert Queue</span>
          </h1>
          <p className="text-[11px] text-[#8995A3] mt-0.5">Triaging queue for suspicious activity flags generated by hybrid rule, behaviour, graph, and ML engines</p>
        </div>

        {/* Priority, Status & Search Filters */}
        <div className="flex flex-wrap items-center gap-3">
          <div className="relative">
            <Search className="w-3.5 h-3.5 text-[#5E6A78] absolute left-2.5 top-2" />
            <input
              type="text"
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              placeholder="Search Alert / Customer..."
              className="bg-[#111820] border border-[#202A35] rounded text-xs text-[#E8EDF2] pl-8 pr-3 py-1 focus:outline-none focus:border-[#3B82F6]"
            />
          </div>

          <div className="flex items-center space-x-2 bg-[#111820] p-1 rounded border border-[#202A35]">
            <Filter className="w-3.5 h-3.5 text-[#5E6A78] ml-1" />
            <select
              value={priorityFilter}
              onChange={(e) => setPriorityFilter(e.target.value)}
              className="bg-transparent text-xs text-[#E8EDF2] font-medium px-2 py-0.5 focus:outline-none"
            >
              <option value="ALL" className="bg-[#111820]">All Priorities</option>
              <option value="CRITICAL" className="bg-[#111820]">Critical</option>
              <option value="HIGH" className="bg-[#111820]">High</option>
              <option value="MEDIUM" className="bg-[#111820]">Medium</option>
              <option value="LOW" className="bg-[#111820]">Low</option>
            </select>
          </div>

          <div className="flex items-center space-x-2 bg-[#111820] p-1 rounded border border-[#202A35]">
            <select
              value={statusFilter}
              onChange={(e) => setStatusFilter(e.target.value)}
              className="bg-transparent text-xs text-[#E8EDF2] font-medium px-2 py-0.5 focus:outline-none"
            >
              <option value="ALL" className="bg-[#111820]">All Statuses</option>
              <option value="PENDING" className="bg-[#111820]">Pending</option>
              <option value="UNDER_INVESTIGATION" className="bg-[#111820]">Under Investigation</option>
              <option value="CLOSED" className="bg-[#111820]">Closed</option>
            </select>
          </div>
        </div>
      </div>

      {/* High Density Workstation Alert Table */}
      <div className="bg-[#111820] border border-[#202A35] rounded-lg p-4">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs font-mono border-collapse">
            <thead>
              <tr className="border-b border-[#202A35] text-[10px] font-bold text-[#5E6A78] uppercase tracking-wider font-sans">
                <th className="py-2.5 px-3">Alert ID</th>
                <th className="py-2.5 px-3">Customer ID</th>
                <th className="py-2.5 px-3">AML Typology</th>
                <th className="py-2.5 px-3">Rule Risk</th>
                <th className="py-2.5 px-3">Graph Risk</th>
                <th className="py-2.5 px-3">ML XGBoost</th>
                <th className="py-2.5 px-3">Meta Risk</th>
                <th className="py-2.5 px-3">Priority</th>
                <th className="py-2.5 px-3">Status</th>
                <th className="py-2.5 px-3 text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-[#202A35]/60 text-[#E8EDF2]">
              {filteredAlerts.map((alert) => (
                <tr key={alert.alert_id} className="hover:bg-[#151D26] transition-colors">
                  <td className="py-2 px-3 text-[#3B82F6] font-bold">{alert.alert_id}</td>
                  <td className="py-2 px-3 text-[#B0BAC5]">{alert.customer_id}</td>
                  <td className="py-2 px-3 font-sans">
                    <span className="bg-[#151D26] text-[#B0BAC5] px-2 py-0.5 rounded text-[11px] font-medium border border-[#202A35]">
                      {alert.typology}
                    </span>
                  </td>
                  <td className="py-2 px-3">{alert.rule_risk}%</td>
                  <td className="py-2 px-3">{alert.graph_risk}%</td>
                  <td className="py-2 px-3">{alert.ml_risk}%</td>
                  <td className="py-2 px-3 font-bold text-[#EF4444]">{alert.meta_risk_score}%</td>
                  <td className="py-2 px-3 font-sans">
                    <span className={`px-2 py-0.5 rounded border text-[10px] font-bold ${getPriorityBadge(alert.priority)}`}>
                      {alert.priority}
                    </span>
                  </td>
                  <td className="py-2 px-3 font-sans text-[#8995A3] text-[11px]">{alert.status}</td>
                  <td className="py-2 px-3 text-right font-sans space-x-2">
                    <button
                      onClick={() => handleOpenShap(alert)}
                      className="px-2.5 py-1 bg-[#151D26] text-[#3B82F6] border border-[#202A35] hover:border-[#3B82F6]/50 rounded text-[11px] font-medium inline-flex items-center space-x-1"
                    >
                      <Brain className="w-3 h-3" />
                      <span>SHAP</span>
                    </button>
                    <button
                      onClick={() => navigate(`/investigation?alert=${alert.alert_id}`)}
                      className="px-2.5 py-1 bg-[#3B82F6] text-white hover:bg-[#2563EB] rounded text-[11px] font-medium inline-flex items-center space-x-1"
                    >
                      <Search className="w-3 h-3" />
                      <span>Investigate</span>
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      <SHAPModal 
        isOpen={isShapOpen}
        onClose={() => setIsShapOpen(false)}
        shapData={selectedShap}
        alertId={selectedAlertId}
      />
    </div>
  );
};
